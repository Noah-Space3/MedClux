function createDefaultWeeklySchedule(): DayAvailability[] {
  const days: DayAvailability['dayLabel'][] = [
    'Sunday',
    'Monday',
    'Tuesday',
    'Wednesday',
    'Thursday',
    'Friday',
    'Saturday',
  ];
  return days.map((label, idx) => ({
    dayOfWeek: idx as DayAvailability['dayOfWeek'],
    dayLabel: label,
    isAvailable: idx >= 1 && idx <= 5,
    openTime: '09:00',
    closeTime: '17:00',
    slotDurationMinutes: 30,
    breaks: [{ startTime: '13:00', endTime: '14:00' }],
    consultationTypes: ['in_person', 'video'],
  }));
}

